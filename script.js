document.addEventListener('DOMContentLoaded', () => {
  const html = document.documentElement;

  // Theme
  const themeToggle = document.getElementById('themeToggle');
  const themeIcon = document.getElementById('themeIcon');

  function applyTheme(theme) {
    html.setAttribute('data-theme', theme);
    localStorage.setItem('nova-theme', theme);
    if (themeIcon) themeIcon.textContent = theme === 'dark' ? '☀️' : '🌙';
  }

  applyTheme(localStorage.getItem('nova-theme') || 'dark');
  themeToggle?.addEventListener('click', () => {
    const next = (html.getAttribute('data-theme') || 'dark') === 'dark' ? 'light' : 'dark';
    applyTheme(next);
  });

  // Language
  const langToggle = document.getElementById('langToggle');
  const langLabel = document.getElementById('langLabel');

  function setLanguage(lang) {
    const dict = translations[lang];
    if (!dict) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });
    html.setAttribute('lang', lang);
    localStorage.setItem('nova-lang', lang);
    if (langLabel) langLabel.textContent = lang.toUpperCase();
  }

  setLanguage(localStorage.getItem('nova-lang') || 'es');
  langToggle?.addEventListener('click', () => {
    const next = (localStorage.getItem('nova-lang') || 'es') === 'es' ? 'en' : 'es';
    setLanguage(next);
  });

  // Year
  const yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  // Mobile menu
  const hamburger = document.getElementById('hamburger');
  const mobileMenu = document.getElementById('mobileMenu');

  function closeMobileMenu() {
    hamburger?.classList.remove('active');
    mobileMenu?.classList.remove('open');
    document.body.style.overflow = '';
  }

  hamburger?.addEventListener('click', () => {
    const isOpen = mobileMenu?.classList.contains('open');
    if (isOpen) closeMobileMenu();
    else {
      hamburger.classList.add('active');
      mobileMenu.classList.add('open');
      document.body.style.overflow = 'hidden';
    }
  });

  document.querySelectorAll('.mobile-link').forEach(l => l.addEventListener('click', closeMobileMenu));
  mobileMenu?.addEventListener('click', e => { if (e.target === mobileMenu) closeMobileMenu(); });

  // Navbar scroll
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    navbar?.classList.toggle('scrolled', window.scrollY > 20);
  }, { passive: true });

  // Active link
  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-link');
  window.addEventListener('scroll', () => {
    const scrollY = window.scrollY + 100;
    sections.forEach(section => {
      const top = section.offsetTop;
      const height = section.offsetHeight;
      const id = section.getAttribute('id');
      if (scrollY >= top && scrollY < top + height) {
        navLinks.forEach(link => {
          link.classList.toggle('active', link.getAttribute('href') === `#${id}`);
        });
      }
    });
  }, { passive: true });

  // Toast
  const toast = document.getElementById('toast');
  let toastTimeout;
  function showToast(msg) {
    if (!toast) return;
    toast.textContent = msg;
    toast.classList.add('show');
    clearTimeout(toastTimeout);
    toastTimeout = setTimeout(() => toast.classList.remove('show'), 2800);
  }

  document.querySelectorAll('#downloadBtn, #mainDownload, a[href*="mediafire"]').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = localStorage.getItem('nova-lang') || 'es';
      showToast(translations[lang]["toast.download"]);
    });
  });

  // Reveal
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll('.feature-card, .tool-card').forEach((el, i) => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(20px)';
    el.style.transition = `opacity 0.5s ease ${i * 0.04}s, transform 0.5s ease ${i * 0.04}s`;
    observer.observe(el);
  });

  const style = document.createElement('style');
  style.textContent = `.feature-card.visible, .tool-card.visible { opacity: 1 !important; transform: translateY(0) !important; }`;
  document.head.appendChild(style);

  if (typeof lucide !== 'undefined') lucide.createIcons();
});